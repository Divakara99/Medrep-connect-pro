import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { PGlite } from '@electric-sql/pglite'

const db = new PGlite()
const adminId = '33333333-3333-4333-8333-333333333333'
const migration = await readFile(new URL('../supabase/vacancy_retention_48_hours.sql', import.meta.url), 'utf8')

try {
  await db.exec(`
    CREATE ROLE anon;
    CREATE ROLE authenticated;
    CREATE ROLE service_role;
    CREATE SCHEMA auth;
    CREATE SCHEMA cron;
    CREATE TABLE cron.job (
      jobid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      jobname text UNIQUE,
      schedule text,
      command text
    );
    CREATE FUNCTION cron.unschedule(p_jobid bigint) RETURNS boolean LANGUAGE sql AS $$
      DELETE FROM cron.job WHERE jobid = p_jobid RETURNING true
    $$;
    CREATE FUNCTION cron.schedule(p_jobname text, p_schedule text, p_command text) RETURNS bigint
    LANGUAGE plpgsql AS $$
    DECLARE result bigint;
    BEGIN
      INSERT INTO cron.job (jobname, schedule, command) VALUES (p_jobname, p_schedule, p_command)
      RETURNING jobid INTO result;
      RETURN result;
    END
    $$;
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
      SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
    $$;
    CREATE FUNCTION auth.jwt() RETURNS jsonb LANGUAGE sql STABLE AS $$
      SELECT jsonb_build_object(
        'sub', nullif(current_setting('request.jwt.claim.sub', true), ''),
        'email', coalesce(nullif(current_setting('test.email', true), ''), ''),
        'app_metadata', jsonb_build_object('role', coalesce(nullif(current_setting('test.role', true), ''), 'user')),
        'aal', coalesce(nullif(current_setting('test.aal', true), ''), 'aal1')
      )
    $$;
    CREATE FUNCTION public.is_app_admin() RETURNS boolean LANGUAGE sql STABLE AS $$
      SELECT coalesce(auth.jwt() -> 'app_metadata' ->> 'role' = 'admin', false)
         AND coalesce(auth.jwt() ->> 'aal' = 'aal2', false)
    $$;
    CREATE FUNCTION public.is_vacancy_editor() RETURNS boolean LANGUAGE sql STABLE AS $$
      SELECT coalesce(auth.jwt() -> 'app_metadata' ->> 'role' = 'vacancy_editor', false)
    $$;
    CREATE TABLE public.vacancies (
      id text PRIMARY KEY,
      data jsonb NOT NULL,
      synced_at timestamptz DEFAULT now()
    );
    CREATE TABLE public.vacancy_audit (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      action text NOT NULL CHECK (action IN ('added', 'deleted', 'restored')),
      vacancy_id text NOT NULL,
      title text NOT NULL DEFAULT '',
      company text NOT NULL DEFAULT '',
      category text NOT NULL DEFAULT '',
      role_position text NOT NULL DEFAULT '',
      location text NOT NULL DEFAULT '',
      actor_role text NOT NULL DEFAULT '',
      actor_email text NOT NULL DEFAULT '',
      reason text,
      created_at timestamptz NOT NULL DEFAULT now()
    );
    CREATE FUNCTION public.record_vacancy_audit() RETURNS trigger LANGUAGE plpgsql AS $$
    BEGIN RETURN NEW; END
    $$;
    CREATE TRIGGER record_vacancy_audit AFTER INSERT OR UPDATE ON public.vacancies
      FOR EACH ROW EXECUTE FUNCTION public.record_vacancy_audit();
  `)

  // pg_cron is Supabase-managed and unavailable in the embedded test database;
  // cron.schedule/unschedule are stubbed above, while the migration's SQL body
  // and actual purge/restore RPCs are exercised as normal Postgres functions.
  await db.exec(migration.replace(/CREATE EXTENSION IF NOT EXISTS pg_cron WITH SCHEMA pg_catalog;\s*/i, ''))
  await db.exec(migration.replace(/CREATE EXTENSION IF NOT EXISTS pg_cron WITH SCHEMA pg_catalog;\s*/i, ''))
  const jobs = (await db.query(`SELECT jobname, schedule, command FROM cron.job`)).rows
  assert.equal(jobs.length, 1, 'rerunning the migration replaces rather than duplicates the schedule')
  assert.equal(jobs[0].jobname, 'purge-expired-vacancies')
  assert.equal(jobs[0].schedule, '*/5 * * * *')

  const now = Date.now()
  const oldTime = now - 48 * 60 * 60 * 1000 - 60_000
  const freshTime = now - 10 * 60 * 1000
  await db.query(`INSERT INTO public.vacancies (id, data) VALUES
    ('expired', jsonb_build_object('title','Old','company','Acme','location','Pune','category','Field','rolePosition','Area Manager','deleted',true,'deletedAt',$1::bigint)),
    ('fresh', jsonb_build_object('title','Fresh','company','Acme','location','Pune','category','Field','rolePosition','Key Account Manager','deleted',true,'deletedAt',$2::bigint))`, [oldTime, freshTime])

  await db.exec(`SET request.jwt.claim.sub = '${adminId}'; SET test.role = 'admin'; SET test.email = 'admin@example.org'; SET test.aal = 'aal2'`)
  await assert.rejects(
    db.query(`SELECT public.restore_vacancy('expired')`),
    /48-hour restore period has ended/,
    'the server refuses expired restores even before cleanup runs',
  )
  const restored = (await db.query(`SELECT public.restore_vacancy('fresh') AS result`)).rows[0].result
  assert.equal(restored.ok, true)
  assert.equal(restored.title, 'Fresh')
  const restoredAudit = (await db.query(`SELECT action, role_position FROM public.vacancy_audit WHERE vacancy_id = 'fresh' ORDER BY id DESC LIMIT 1`)).rows[0]
  assert.deepEqual(restoredAudit, { action: 'restored', role_position: 'Key Account Manager' }, 'restore history keeps its custom label')

  const removed = (await db.query(`SELECT public.purge_expired_deleted_vacancies() AS removed`)).rows[0].removed
  assert.equal(removed, 1, 'full vacancy data is physically purged after 48 hours')
  const remaining = (await db.query(`SELECT id FROM public.vacancies ORDER BY id`)).rows.map((row) => row.id)
  assert.deepEqual(remaining, ['fresh'], 'a recent tombstone remains available to restore')
  const scheduleCount = (await db.query(`SELECT count(*)::int AS n FROM cron.job WHERE command = 'SELECT public.purge_expired_deleted_vacancies();'`)).rows[0].n
  assert.equal(scheduleCount, 1, 'the scheduled job calls the safe purge function once')
  console.log('vacancy retention: database-enforced 48-hour restore, permanent purge, role-position audit, and idempotent five-minute cleanup schedule passed')
} finally {
  await db.close()
}
